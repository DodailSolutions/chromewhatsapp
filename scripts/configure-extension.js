// Points a copy of the Reach extension at this server and its signing key.
//   node scripts/configure-extension.js <extension-folder> <server-url>
//   e.g. node scripts/configure-extension.js ../dodail-reach-extension https://license.dodail.com
// Reads LICENSE_PRIVATE_KEY from the environment or .env.local and writes license-config.js (public key only).
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import { loadEnv } from "./env.js";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
loadEnv(ROOT);
const [extDir, url] = process.argv.slice(2);
if (!extDir || !url || !/^https?:\/\/[^/]+/.test(url)) { console.error("Usage: node scripts/configure-extension.js <extension-folder> <server-url>"); process.exit(1); }
if (!fs.existsSync(path.join(extDir, "manifest.json"))) { console.error(`${extDir} has no manifest.json`); process.exit(1); }
const pem = String(process.env.LICENSE_PRIVATE_KEY || "").replace(/\\n/g, "\n");
if (!pem.includes("PRIVATE KEY")) { console.error("Set LICENSE_PRIVATE_KEY (or run npm run setup -- --write first)."); process.exit(1); }
const j = crypto.createPublicKey(pem).export({ format: "jwk" });
const out = `// Generated by configure-extension.js on ${new Date().toISOString().slice(0, 10)}. The public key only verifies licenses; it can't create them.
self.REACH_LICENSE_CONFIG = {
  server: ${JSON.stringify(url.replace(/\/+$/, ""))},
  publicKey: ${JSON.stringify({ kty: j.kty, crv: j.crv, x: j.x, y: j.y })}
};
`;
fs.writeFileSync(path.join(extDir, "license-config.js"), out);
console.log(`Done: ${path.join(extDir, "license-config.js")} → ${url}`);
